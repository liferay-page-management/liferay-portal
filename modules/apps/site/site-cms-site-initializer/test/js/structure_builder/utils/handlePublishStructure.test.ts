const EMPTY_HISTORY = {
	deletedChildren: [],
	deletedGroupERCs: [],
	deletedRelationships: [],
	modifiedNames: new Set<Uuid>(),
	modifiedSlugs: new Set<Uuid>(),
};

function field(name: string, uuid: Uuid, parent: Uuid): Field {
	return {
		erc: `${name}-erc`,
		indexableConfig: {indexed: false},
		label: {en_US: name},
		localized: false,
		locked: false,
		name,
		parent,
		required: false,
		settings: {},
		type: 'text',
		uuid,
	};
}

const STRUCTURE_UUID = getUuid();

function buildState(type: StructureType, children: StructureChild[]): State {
	const structure: Structure = {
		children: new Map(children.map((child) => [child.uuid, child])),
		erc: 'erc',
		label: {en_US: 'Structure'},
		name: 'Structure',
		path: '',
		slug: '',
		spaces: 'all',
		status: 'published',
		system: false,
		type,
		uuid: STRUCTURE_UUID,
		workflows: {},
	};

	return {
		clipboard: null,
		history: EMPTY_HISTORY,
		invalids: new Map(),
		operation: null,
		publishedChildren: new Set(),
		renamingItemUuid: null,
		savedChildren: new Set(),
		selection: [],
		structure,
		unsavedChanges: false,
	};
}

function publish(state: State) {
	return handlePublishStructure({
		dispatch: jest.fn(),
		objectDefinitions: {},
		showExperienceLink: false,
		showWarnings: false,
		spaces: [],
		staleCache: jest.fn(),
		state,
		validate: () => true,
	});
}

describe('handlePublishStructure - object layout persistence', () => {
	beforeEach(() => {
		jest.clearAllMocks();

		jest.spyOn(
			Liferay.ThemeDisplay,
			'getDefaultLanguageId'
		).mockReturnValue('en_US');
		jest.spyOn(Liferay.ThemeDisplay, 'getLanguageId').mockReturnValue(
			'en_US'
		);

		(StructureService.updateStructure as jest.Mock).mockResolvedValue({
			error: null,
		});
		(
			DisplayPageService.resetTranslationDisplayPage as jest.Mock
		).mockResolvedValue(undefined);
	});

	afterEach(() => {
		jest.restoreAllMocks();
	});

	it('persists the object layout when publishing a structure with groups', async () => {
		const title = field('title', getUuid(), STRUCTURE_UUID);
		const rootGroupUuid = getUuid();
		const sku = field('sku', getUuid(), rootGroupUuid);

		const rootGroup: Group = {
			children: new Map([[sku.uuid, sku]]),
			isRepeatable: false,
			label: {en_US: 'Details'},
			parent: STRUCTURE_UUID,
			type: 'group',
			uuid: rootGroupUuid,
		};

		await publish(buildState('L_CUSTOM_STRUCTURES', [title, rootGroup]));
	});
});
